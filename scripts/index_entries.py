#!/usr/bin/env python3
"""Apply add / delete / rename / describe operations to category files, then
re-sort entries alphabetically within each section.

Usage: python3 scripts/index_entries.py ops.json [--dry-run]

ops.json is a list of objects:
  {"op": "add", "file": "07-mcp.md", "name": "Canopy", "url": "https://github.com/...",
   "badges": "![Template](...)", "desc": "One or two sentences."}
  {"op": "delete", "url": "https://github.com/danielrosehill/Old-Repo"}
  {"op": "rename", "url": "<old url>", "new_url": "<new url>", "name": "New Title"}
  {"op": "describe", "url": "<url>", "desc": "New description."}
  {"op": "move", "url": "<url>", "file": "03-research.md"}   # appended to that file's first section

URLs match case-insensitively. A section is the run of entries under one `#`/`##`
heading; sorting never crosses a heading, so subsections keep their own order.
08-plugins.md is generated by sync_marketplace.py and is refused.
"""
import json
import re
import sys
from pathlib import Path

CATS = Path(__file__).resolve().parent.parent / "categories"
BADGE = "[![View Repo](https://img.shields.io/badge/View%20Repo-blue?style=flat-square&logo=github)]"
URL_RE = re.compile(r"\]\((https://github\.com/[^)]+)\)")


def parse(text):
    """Return list of sections: {"head": [lines], "entries": [[lines], ...]}."""
    sections, cur, entry = [], {"head": [], "entries": []}, None
    for line in text.split("\n"):
        if line.startswith("### "):
            entry = [line]
            cur["entries"].append(entry)
        elif line.startswith("#"):
            if cur["head"] or cur["entries"]:
                sections.append(cur)
            cur, entry = {"head": [line], "entries": []}, None
        elif entry is not None:
            entry.append(line)
        else:
            cur["head"].append(line)
    sections.append(cur)
    return sections


def render(sections):
    out = []
    for s in sections:
        out += s["head"]
        for e in s["entries"]:
            out += e
    return "\n".join(out)


def entry_url(e):
    for line in e:
        if line.startswith("[![View Repo]"):
            m = URL_RE.search(line)
            return m.group(1).rstrip("/").lower() if m else None
    return None


def normalise(e):
    while e and e[-1] == "":
        e.pop()
    if e[-1] != "---":
        e += ["", "---"]
    e.append("")
    return e


def make_entry(name, url, badges, desc):
    badge_line = f"{BADGE}({url})" + (f" {badges}" if badges else "")
    return [f"### {name}", badge_line, "", desc, "", "---", ""]


def main():
    ops = json.loads(Path(sys.argv[1]).read_text())
    dry = "--dry-run" in sys.argv
    files = {p.name: parse(p.read_text()) for p in sorted(CATS.glob("*.md"))
             if p.name not in ("00-header.md", "08-plugins.md")}

    def find(url):
        u = url.rstrip("/").lower()
        for fname, secs in files.items():
            for s in secs:
                for i, e in enumerate(s["entries"]):
                    if entry_url(e) == u:
                        return fname, s, i
        raise SystemExit(f"not found: {url}")

    for op in ops:
        kind = op["op"]
        if op.get("file") == "08-plugins.md":
            raise SystemExit("08-plugins.md is generated; edit the marketplace instead")
        if kind == "add":
            try:
                find(op["url"])
                print(f"skip (already indexed): {op['url']}")
                continue
            except SystemExit:
                pass
            secs = files[op["file"]]
            target = next((s for s in secs if s["entries"]), secs[-1])
            target["entries"].append(make_entry(op["name"], op["url"], op.get("badges", ""), op["desc"]))
        elif kind == "delete":
            _, s, i = find(op["url"])
            s["entries"].pop(i)
        elif kind == "rename":
            _, s, i = find(op["url"])
            e = s["entries"][i]
            if op.get("name"):
                e[0] = f"### {op['name']}"
            for j, line in enumerate(e):
                if line.startswith("[![View Repo]"):
                    e[j] = URL_RE.sub(f"]({op['new_url']})", line, count=1)
        elif kind == "describe":
            _, s, i = find(op["url"])
            e = s["entries"][i]
            # description = non-empty lines after the badge line, before '---'
            body = [j for j, l in enumerate(e[2:], 2) if l.strip() and l.strip() != "---"
                    and not l.startswith(("[![", "!["))]
            if not body:
                raise SystemExit(f"no description found: {op['url']}")
            e[body[0]:body[-1] + 1] = [op["desc"]]
        elif kind == "move":
            _, s, i = find(op["url"])
            e = s["entries"].pop(i)
            secs = files[op["file"]]
            next((x for x in secs if x["entries"]), secs[-1])["entries"].append(e)
        else:
            raise SystemExit(f"unknown op {kind}")

    for fname, secs in files.items():
        for s in secs:
            s["entries"] = [normalise(e) for e in s["entries"]]
            s["entries"].sort(key=lambda e: e[0][4:].strip().casefold())
        new = render(secs)
        path = CATS / fname
        if new != path.read_text():
            print(f"{'would change' if dry else 'changed'}: {fname}")
            if not dry:
                path.write_text(new)


if __name__ == "__main__":
    main()
